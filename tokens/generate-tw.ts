// The Tailwind experiment: writes src/styles-tw/theme.css, a Tailwind v4 `@theme inline` that maps
// Tailwind's namespaces onto the `--damsko-*` variables tokens.css already defines, so `bg-primary`,
// `text-muted-foreground`, `rounded-xl`, `shadow-sm`, `h-control-sm` and `p-3` resolve to the same
// values the StyleX components read. No value is written here: every entry is a var().
//
//   node tokens/generate-tw.ts
import { writeFileSync } from "node:fs";
import nodePath from "node:path";

import { breakpoints, groups } from "./tokens.ts";
import type { Token } from "./tokens.ts";

const all: Token[] = groups.flatMap((group) =>
  group.sets.flatMap((set) => set.tokens)
);
const byName = new Map(all.map((token) => [token.name, token]));

/** The value with every `{ref}` replaced by its own value, for telling a length from the rest. */
const resolved = (value: string): string =>
  value.replaceAll(/\{(?<name>[a-z0-9-]+)\}/gu, (_, name: string) =>
    resolved(byName.get(name)?.value ?? "")
  );

const LENGTH = /^-?\d*\.?\d+(?:px|rem|em|ch|dvh|svh|vh|vw|%)$/u;
const isLength = (value: string) => {
  const plain = resolved(value).trim();
  return LENGTH.test(plain) || /^(?:max|min|calc)\(/u.test(plain);
};

const lines: string[] = [];
const scales: Record<string, string[]> = {};
const map = (key: string, token: string) => {
  lines.push(`  --${key}: var(--damsko-${token});`);
  // The names tailwind-merge must know, by its theme scale, or it reads `text-heading-xs` as a
  // colour and drops it beside `text-foreground`.
  const scale = [
    ["color-", "color"],
    ["shadow-", "shadow"],
    ["spacing-", "spacing"],
    ["radius-", "radius"],
    ["leading-", "leading"],
    ["tracking-", "tracking"],
    ["font-weight-", "font-weight"],
    ["ease-", "ease"],
    ["text-", "text"],
    ["font-", "font"],
  ].find(([prefix]) => key.startsWith(prefix ?? ""));
  if (scale !== undefined && !key.includes("--")) {
    const [prefix = "", name = ""] = scale;
    (scales[name] ??= []).push(key.slice(prefix.length));
  }
};

const mapped = {
  color: 0,
  shadow: 0,
  text: 0,
  spacing: 0,
  radius: 0,
  other: 0,
  left: 0,
};
for (const token of all) {
  const { name, category } = token;
  if (category === "colors") {
    map(`color-${name}`, name);
    mapped.color += 1;
  } else if (category === "shadow") {
    map(`shadow-${name.replace(/^shadow-/u, "")}`, name);
    mapped.shadow += 1;
  } else if (category === "font") {
    if (/^font-(?:sans|serif|mono)$/u.test(name)) {
      map(name, name);
    } else if (name.startsWith("font-weight-")) {
      map(name, name);
    } else if (name.startsWith("tracking-")) {
      map(name, name);
    } else if (/^(?:text|heading)-[a-z0-9]+$/u.test(name)) {
      const key = name.startsWith("heading") ? `text-${name}` : name;
      map(key, name);
      if (byName.has(`${name}-line`)) {
        map(`${key}--line-height`, `${name}-line`);
      }
    } else if (name.endsWith("-line")) {
      // text-xs-line and the like are written with their size above.
      if (!byName.has(name.slice(0, -"-line".length))) {
        map(`leading-${name.slice(0, -"-line".length)}`, name);
      }
    } else if (name.startsWith("shimmer-")) {
      map(`color-${name}`, name);
    } else if (/weight/u.test(name)) {
      map(`font-weight-${name.replace(/-weight/u, "")}`, name);
    } else {
      mapped.left += 1;
      continue;
    }
    mapped.text += 1;
  } else if (category === "space") {
    if (/^space-\d+$/u.test(name)) {
      continue;
    }
    map(`spacing-${name}`, name);
    mapped.spacing += 1;
  } else if (category === "radius") {
    if (name === "radius" || name === "radius-shape") {
      continue;
    }
    map(
      `radius-${name.replace(/^radius-/u, "").replace(/-radius$/u, "")}`,
      name
    );
    mapped.radius += 1;
  } else if (category === "size") {
    if (name.endsWith("-tracking")) {
      map(`tracking-${name.slice(0, -"-tracking".length)}`, name);
      mapped.other += 1;
    } else if (isLength(token.value)) {
      map(`spacing-${name}`, name);
      mapped.spacing += 1;
    } else {
      mapped.left += 1;
    }
  } else if (category === "duration") {
    if (name === "ease") {
      map("ease-ui", name);
    } else if (name === "ease-in-out") {
      map("ease-ui-in-out", name);
    } else {
      mapped.left += 1;
    }
  }
}

const out = `/* Generated by \`node tokens/generate-tw.ts\` from tokens/ (the Tailwind experiment). Do not edit.
   Tailwind's theme, mapped onto Damsko's variables: load tokens.css first. ${all.length} tokens:
   ${mapped.color} colours, ${mapped.shadow} shadows, ${mapped.text} type, ${mapped.spacing} lengths, ${mapped.radius} corners,
   ${mapped.other} tracking; ${mapped.left} (times, scales, opacities, composite shadows) have no
   Tailwind namespace and are read as \`duration-(--damsko-duration-hover)\`. */
@theme inline {
  --spacing: var(--damsko-space-1);
${lines.join("\n")}
}

/* Media queries cannot read a variable: the breakpoints are written as values. */
@theme {
${breakpoints.map((point) => `  --breakpoint-${point.name}: ${point.value};`).join("\n")}
}
`;

writeFileSync(
  nodePath.join(import.meta.dirname, "../src/styles-tw/theme.css"),
  out
);
writeFileSync(
  nodePath.join(import.meta.dirname, "../src/lib-tw/merge-theme.ts"),
  `// Generated by \`node tokens/generate-tw.ts\` (the Tailwind experiment). Do not edit.
// Damsko's theme names by tailwind-merge's scale, so cn() knows \`text-heading-xs\` is a size and
// \`shadow-bevel-ink\` a shadow.
export const mergeTheme = ${JSON.stringify(scales, null, 2)};
`
);
