// Writes the token files from tokens/tokens.ts and tokens/themes.ts:
//
//   src/styles/tokens.css        CSS custom properties (--damsko-*), light and dark through light-dark()
//   src/styles/themes.css        the modes, and every colour token restated per theme ([data-theme])
//   src/lib/tokens.stylex.ts     typed StyleX names, one object per category, that refer to those
//                                properties, and the breakpoints and interaction queries (media.*)
//   src/lib/tokens.values.ts     the motion times, breakpoints and popup distances as numbers
//
//   pnpm run generate                  write them
//   node tokens/generate.ts --check    fail when a file is out of date, a reference is broken, a
//                                      colour is not on the brand list, or a pair falls under its
//                                      contrast floor in any theme
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { cornerFallbacks } from "./corner-fallbacks.ts";
import {
  camel,
  carriesColour,
  cssValue,
  cssVar,
  indexTokens,
  isColourValue,
  measurePair,
  offBrand,
  resolver,
  stylexKey,
  themer,
} from "./model.ts";
import { themes } from "./themes.ts";
import { brand, breakpoints, contrastPairs, groups } from "./tokens.ts";
import type { Category, Token } from "./tokens.ts";

const root = fileURLToPath(new URL("..", import.meta.url));

const HEADER =
  "Generated by `pnpm run generate` from tokens/. Do not edit: change the source and run it again.";

const CATEGORIES: readonly Category[] = [
  "colors",
  "space",
  "radius",
  "shadow",
  "font",
  "duration",
  "size",
];

const all: Token[] = groups.flatMap((group) =>
  group.sets.flatMap((set) => set.tokens)
);
const byName = indexTokens(all);
const resolve = resolver(byName);
const isColourToken = (name: string) =>
  isColourValue(resolve(name, "light")) && isColourValue(resolve(name, "dark"));

for (const name of Object.keys(cornerFallbacks)) {
  const token = byName.get(name);
  if (token === undefined) {
    throw new Error(`Corner fallback ${name} is not a token.`);
  }
}

/** The tokens by their group and set, as the files list them. */
const sets = groups.flatMap((group) =>
  group.sets.map((set) => ({
    title: `${group.title}: ${set.title.toLowerCase()}.`,
    tokens: set.tokens,
  }))
);
const css = () => {
  const lines = [
    `/* ${HEADER} */`,
    "/* Colours and shadows with a dark value use light-dark(), which follows the color-scheme of the",
    "   element that uses them: set color-scheme on :root (light, dark, or both) and on any part that",
    "   stands on another ground (color-scheme: dark on a night band). */",
    ":root {",
  ];
  for (const set of sets.filter((each) => each.tokens.length > 0)) {
    lines.push(`  /* ${set.title} */`);
    for (const token of set.tokens) {
      lines.push(
        `  /* ${token.use} */`,
        `  ${cssVar(token.name)}: ${cssValue(token.name, token, cssVar, isColourToken)};`
      );
    }
  }
  lines.push(
    "  /* Breakpoints, for scripts. A media query cannot read them: see lib/tokens.stylex.ts. */"
  );
  for (const point of breakpoints) {
    lines.push(
      `  /* ${point.use} */`,
      `  ${cssVar(`breakpoint-${point.name}`)}: ${point.value};`
    );
  }
  lines.push(
    "}",
    "",
    "/* Where a browser draws no squircle, each squircle corner as the plain radius that reads like it. */",
    "@supports not (corner-shape: squircle) {",
    "  :root {"
  );
  for (const [name, value] of Object.entries(cornerFallbacks)) {
    lines.push(`    ${cssVar(name)}: ${value};`);
  }
  lines.push("  }", "}", "");
  return lines.join("\n");
};

const themesCss = () => {
  const lines = [
    `/* ${HEADER} */`,
    "/* Modes: light, dark, or the system's, on any element. With no mode set, the system's setting",
    "   wins; :where() keeps that rule weaker than any a host page writes. */",
    ":where(:root:not([data-mode])) { color-scheme: light dark; }",
    '[data-mode="light"] { color-scheme: light; }',
    '[data-mode="dark"] { color-scheme: dark; }',
    '[data-mode="system"] { color-scheme: light dark; }',
    "/* Themes: every colour token restated, so references follow the theme on any subtree. */",
  ];
  for (const theme of themes) {
    const { values } = themer(byName, theme);
    lines.push(`[data-theme="${theme.id}"] {`);
    for (const token of all.filter(carriesColour)) {
      lines.push(
        `  ${cssVar(token.name)}: ${cssValue(token.name, values(token), cssVar, () => true)};`
      );
    }
    lines.push("}");
  }
  // In forced colours the system's colours win: a theme and a mode yield, so the system's own
  // light or dark palette is drawn whatever a person chose.
  lines.push(
    "@media (forced-colors: active) { [data-theme], [data-mode] { color-scheme: light dark; } }",
    ""
  );
  return lines.join("\n");
};

const pascal = (name: string) =>
  camel(name).replace(/^./u, (first) => first.toUpperCase());

/** A key as an object literal writes it: quoted when it is not an identifier (`"4"`). */
const keyOf = (key: string) =>
  /^[A-Za-z_$][\w$]*$/u.test(key) ? key : `"${key}"`;

const stylex = () => {
  const lines = [
    `// ${HEADER}`,
    "//",
    "// Every StyleX name refers to its CSS custom property in styles/tokens.css; no value is written",
    "// here. Constants (not defineVars) because the variables already exist: StyleX inlines",
    "// `var(--damsko-…)` at build time and emits no second set of properties. Load tokens.css once",
    "// on the page. One object per category: `colors.primary`, `space[4]`, `radius.base`.",
    'import * as stylex from "@stylexjs/stylex";',
  ];
  for (const category of CATEGORIES) {
    lines.push("", `export const ${category} = stylex.defineConsts({`);
    const keys = new Set<string>();
    for (const set of sets) {
      const tokens = set.tokens.filter((token) => token.category === category);
      if (tokens.length === 0) {
        continue;
      }
      lines.push(`  // ${set.title}`);
      for (const token of tokens) {
        const key = stylexKey(token.name, category);
        if (keys.has(key)) {
          throw new Error(
            `Two ${category} tokens are both ${category}.${key}.`
          );
        }
        keys.add(key);
        lines.push(`  ${keyOf(key)}: "var(${cssVar(token.name)})",`);
      }
    }
    lines.push("});");
  }
  const first = breakpoints[0]?.value ?? "40rem";
  lines.push(
    "",
    "// Media queries, as constants: a media query cannot read a CSS variable, so the breakpoints are",
    "// written into the queries here. Use them as keys: `{ [media.maxSm]: ... }`.",
    "export const media = stylex.defineConsts({"
  );
  for (const point of breakpoints) {
    lines.push(
      `  max${pascal(point.name)}: "@media (width < ${point.value})",`,
      `  ${point.name}: "@media (width >= ${point.value})",`
    );
  }
  lines.push(
    '  hover: "@media (hover: hover) and (pointer: fine)",',
    '  pointerCoarse: "@media (pointer: coarse)",',
    // Where typed text is the touch size (16px): a phone's width or a touch screen, where Safari
    // zooms the page in when a field with smaller text takes focus.
    `  maxSmOrCoarse: "@media (width < ${first}), (pointer: coarse)",`,
    '  reducedMotion: "@media (prefers-reduced-motion: reduce)",',
    '  forcedColors: "@media (forced-colors: active)",',
    // With no script: nothing can be opened, so what would be folded or closed shows whole.
    '  noScript: "@media (scripting: none)",',
    "});",
    ""
  );
  return lines.join("\n");
};

// The popup distances UI SDK takes as numbers, not CSS: it places a popup by pixels.
const POPUP = [
  "popup-gap",
  "popup-gutter",
  "popover-gap",
  "tooltip-gap",
  "menu-gap",
  "date-picker-field-padding",
] as const;

// The wave of light Skeleton works out in a script, pass by pass: plain numbers.
const WAVE = [
  "skeleton-wave-speed",
  "skeleton-wave-rest",
  "skeleton-wave-slope",
] as const;

const values = () => {
  const lines = [
    `// ${HEADER}`,
    "//",
    "// The motion times in milliseconds, for scripts that must wait. Styles use tokens.stylex.ts.",
    "export const durations = {",
  ];
  const keys = new Set<string>();
  for (const token of all) {
    if (/^\d+ms$/u.test(token.value)) {
      const key = stylexKey(token.name, token.category);
      if (keys.has(key)) {
        throw new Error(`Two times are both durations.${key}.`);
      }
      keys.add(key);
      lines.push(`  ${key}: ${Number(token.value.slice(0, -2))},`);
    }
  }
  lines.push(
    "} as const;",
    "",
    "/** The breakpoints in CSS pixels (1rem = 16px). */",
    "export const px = {",
    ...breakpoints.map(
      (point) =>
        `  ${point.name}: ${Number(point.value.replace(/rem$/u, "")) * 16},`
    ),
    "} as const;",
    "",
    "/** Popup distances in CSS pixels, for UI SDK's positioning (sideOffset, collisionPadding). */",
    "export const popup = {"
  );
  for (const name of POPUP) {
    const value = resolve(name, "light");
    if (!/^\d+(?:\.\d+)?px$/u.test(value)) {
      throw new Error(
        `Token ${name} must be in px to be written as a number; it is ${value}.`
      );
    }
    lines.push(
      `  ${camel(name.replace(/^popup-/u, ""))}: ${Number(value.slice(0, -2))},`
    );
  }
  lines.push(
    "} as const;",
    "",
    "/** The wave of light a Skeleton's script works out: its speed (px a second), rest and slope. */",
    "export const skeletonWave = {"
  );
  for (const name of WAVE) {
    const value = resolve(name, "light");
    if (!/^\d+(?:\.\d+)?$/u.test(value)) {
      throw new Error(`Token ${name} must be a plain number; it is ${value}.`);
    }
    lines.push(
      `  ${camel(name.replace(/^skeleton-wave-/u, ""))}: ${Number(value)},`
    );
  }
  lines.push("} as const;", "");
  return lines.join("\n");
};

const files: Record<string, string> = {
  "src/lib/tokens.stylex.ts": stylex(),
  "src/lib/tokens.values.ts": values(),
  "src/styles/themes.css": themesCss(),
  "src/styles/tokens.css": css(),
};

const problems = [
  ...offBrand(all, brand, themes).map(
    ({ token, colour }) =>
      `Brand: ${token} has ${colour}, which is not on the brand list (tokens/tokens.ts, brand). Use a brand colour.`
  ),
  ...[
    { id: "", resolve },
    ...themes.map((theme) => ({ id: theme.id, ...themer(byName, theme) })),
  ].flatMap((theme) =>
    contrastPairs
      .map((pair) => measurePair(pair, theme.resolve))
      .filter((pair) => !pair.pass)
      .map(
        (pair) =>
          `Contrast${theme.id === "" ? "" : ` (${theme.id})`}: ${pair.text} on ${pair.on} is ${pair.light}:1 light, ${pair.dark}:1 dark; it needs ${pair.floor}:1 in both.`
      )
  ),
];
for (const problem of problems) {
  console.error(problem);
}

const count = `${all.length} tokens`;
if (process.argv.includes("--check")) {
  const current = await Promise.all(
    Object.keys(files).map(async (file) => {
      try {
        return await readFile(path.join(root, file), "utf-8");
      } catch {
        return "";
      }
    })
  );
  const stale = Object.entries(files)
    .filter(([, content], index) => current[index] !== content)
    .map(([file]) => file);
  for (const file of stale) {
    console.error(`Out of date: ${file}. Run pnpm run generate.`);
  }
  if (stale.length > 0 || problems.length > 0) {
    process.exit(1);
  }
  console.log(
    `Tokens are up to date: ${count}, ${contrastPairs.length} contrast pairs pass in ${themes.length} themes.`
  );
} else {
  await Promise.all(
    Object.entries(files).map(async ([file, content]) => {
      await mkdir(path.dirname(path.join(root, file)), { recursive: true });
      await writeFile(path.join(root, file), content);
    })
  );
  console.log(`Wrote ${Object.keys(files).join(", ")}: ${count}.`);
  if (problems.length > 0) {
    process.exit(1);
  }
}
